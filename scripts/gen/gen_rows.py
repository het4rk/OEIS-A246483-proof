import sympy as sp, re, subprocess
k,e,x=sp.symbols('k e x')
NMAX=7
F_=['A','B','Bm','C','Cm','D','Dm','E','E1','E2','E3']
def S(s,ee):
    g=dict(zip(F_,s))
    Sxx=g['A']+ee*g['Bm']+(k-1-ee)*g['B']; Snm=g['C']+g['D']+ee*g['E3']+(k-3-ee)*g['E']
    Sxm=g['Dm']+(k-1-ee)*g['E1']; Sym=g['Cm']+(k-1-ee)*g['E2']
    return g,Sxx,Snm,Sxm,Sym
def step(s,ee):
    g,Sxx,Snm,Sxm,Sym=S(s,ee)
    return [sp.expand(t) for t in [Sxx,Snm,Sym,Snm,Sxm,Sxx-g['B'],Sxx-g['Bm'],Snm-g['E'],Snm-g['E3'],Sxm-g['E1'],Sym-g['E2']]]
def F(s,ee):
    g,Sxx,Snm,Sxm,Sym=S(s,ee)
    Rx=Sxx+ee*Sym+(k-1-ee)*Snm; Rm=(k+1-ee)*Sxm
    return sp.expand(ee*Rm+(k+1-ee)*Rx)
W={0:[[1]*11],1:[[1]*11]}
We=[[sp.Integer(1)]*11]; Wo=[[sp.Integer(1)]*11]
for n in range(NMAX): We.append(step(We[-1],1)); Wo.append(step(Wo[-1],0))
Pe=[F(We[n],1) for n in range(NMAX+1)]; Po=[F(Wo[n],0) for n in range(NMAX+1)]
# brute-force sanity
import itertools
def brute(n,kk):
    L=n+3;c=0
    for w in itertools.product(range(kk+1),repeat=L):
        if all(w[i]+w[j]!=kk for i in range(L) for j in range(i+1,min(L,i+4))): c+=1
    return c
for n in range(1,4):
    for kk in range(0,5):
        P=Pe[n] if kk%2==0 else Po[n]
        assert P.subs(k,kk)==brute(n,kk),(n,kk)
def L(p): return str(sp.expand(p)).replace('**','^')
def Lk(p): return L(p).replace('k','(k : ℤ)')
def rec(n):
    a=sp.Poly(sp.expand((1-x)**(n+4)*(1+x)**(n+1)),x).all_coeffs()[::-1]
    return [-int(c) for c in a[1:]]  # a(j)=sum r[i-1] a(j-i)
out=["import A246479Rows.Eps\n\n/-!\n# Rows of OEIS A246479 (generated by `gen/gen_rows.py`)\n\n`We n k` / `Wo n k` are the type vectors after `n` steps for even / odd `k`.\n-/\n\nset_option maxHeartbeats 4000000\n\nnamespace A246479\n"]
for tag,Wl,ee in [('We',We,1),('Wo',Wo,0)]:
    for n in range(NMAX+1):
        out.append(f"/-- type vector after {n} steps, {'even' if ee else 'odd'} `k` -/\ndef {tag}{n} (k : ℤ) : St :=\n  ⟨"+",\n    ".join(L(t) for t in Wl[n])+"⟩\n")
    hyp=f"(he : eps k = {ee})"
    out.append(f"lemma V_{tag}0 {{k : ℕ}} : V k 0 = {tag}0 (k : ℤ) := by\n  rfl\n")
    for n in range(NMAX):
        out.append(f"lemma V_{tag}{n+1} {{k : ℕ}} {hyp} : V k {n+1} = {tag}{n+1} (k : ℤ) := by\n  show step k (V k {n}) = _\n  rw [V_{tag}{n}{' he' if n>0 else ''}]\n  ext <;> simp only [step, Sxx, Snm, Sxm, Sym, {tag}{n}, {tag}{n+1}, he, Nat.cast_one, Nat.cast_zero] <;> ring\n")
    P=Pe if ee else Po
    for n in range(1,NMAX+1):
        out.append(f"lemma F_{tag}{n} {{k : ℕ}} {hyp} : F k ({tag}{n} (k : ℤ)) = {Lk(P[n])} := by\n  simp only [F, Rm, Rx, Sxx, Snm, Sxm, Sym, {tag}{n}, he, Nat.cast_one, Nat.cast_zero]; ring\n")
thms=[]
for n in range(1,NMAX+1):
    A2=sp.expand(Pe[n]+Po[n]); D=sp.expand(Pe[n]-Po[n])
    out.append(f"/-- Row {n} as a quasi-polynomial in `k`: even part degree {n+3}, alternating part degree {n}. -/\ntheorem row{n}_quasi (k : ℕ) :\n    2 * (T {n} k : ℤ) = {Lk(A2)} + (-1) ^ k * ({Lk(D)}) := by\n  rcases Nat.even_or_odd k with hk | hk\n  · rw [T_eq_F, V_We{n} (eps_even hk), F_We{n} (eps_even hk), hk.neg_one_pow]; ring\n  · rw [T_eq_F, V_Wo{n} (eps_odd hk), F_Wo{n} (eps_odd hk), hk.neg_one_pow]; ring\n")
    out.append(f"theorem row{n}_even {{k : ℕ}} (hk : Even k) : (T {n} k : ℤ) = {Lk(Pe[n])} := by\n  rw [T_eq_F, V_We{n} (eps_even hk), F_We{n} (eps_even hk)]\n")
    out.append(f"theorem row{n}_odd {{k : ℕ}} (hk : Odd k) : (T {n} k : ℤ) = {Lk(Po[n])} := by\n  rw [T_eq_F, V_Wo{n} (eps_odd hk), F_Wo{n} (eps_odd hk)]\n")
    r=rec(n); d=len(r)
    rhs=" + ".join(f"({c}) * (T {n} (j - {i+1}) : ℤ)" for i,c in enumerate(r) if c!=0)
    sh=", ".join(f"show m + {d} - {i+1} = m + {d-i-1} by omega" for i,c in enumerate(r) if c!=0)
    hs="\n".join(f"  have h{t} := row{n}_quasi (m + {t}); push_cast at h{t}" for t in range(d+1))
    lc=f"h{d} - (" + " + ".join(f"({c}) * h{d-i-1}" for i,c in enumerate(r) if c!=0)+")"
    out.append(f"/-- Hardin's empirical row-{n} recurrence (order {d}), in OEIS indexing `a(j) = T({n}, j)`; valid for all `j ≥ {d}`. -/\ntheorem row{n}_rec (j : ℕ) (hj : {d} ≤ j) :\n    (T {n} j : ℤ) = {rhs} := by\n  obtain ⟨m, rfl⟩ : ∃ m, j = m + {d} := ⟨j - {d}, by omega⟩\n  rw [{sh}]\n  simp only [add_zero]\n{hs}\n  have key : 2 * (T {n} (m + {d}) : ℤ) = 2 * ({rhs.replace('(j - ','(m + ').replace(f'T {n} (m + ',f'T {n} (m + X')}) := by\n    linear_combination {lc}\n  exact mul_left_cancel₀ (by norm_num : (2 : ℤ) ≠ 0) key\n")
    thms.append((n,d,r))
out.append("end A246479\n")
s="\n".join(out)
# fix the key rhs indices: replace 'T n (m + Xi)' where i was the shift i+1 -> m + d-i-1
def fixkey(s):
    for n,d,r in thms:
        for i in range(d):
            s=s.replace(f"T {n} (m + X{i+1})",f"T {n} (m + {d-i-1})")
    return s
s=fixkey(s).replace("(m + 0)","m")
